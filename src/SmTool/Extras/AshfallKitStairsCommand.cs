using System.Globalization;
using System.Numerics;
using System.Text;
using SmSim.Extras.Musou.Ashfall;

namespace SmTool;

/// <summary>
/// <c>smtool ashfall-kit-stairs [--source dir] [--out file]</c> (late batch F, 2026-11-06): reads each walkable kit model's GLB from the owner's private library (read only), finds its stairs in its own mesh
/// (<see cref="AshfallStairDetect"/>) and writes the numbers as <c>AshfallKitStairs.g.cs</c> (committed; numbers only, no asset bytes). The level lays one ramp over each stair (docs/musou-ashfall-graybox.md "Draft 9").
/// </summary>
static class AshfallKitStairsCommand
{
    public static int Run(string[] rest)
    {
        string local = Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData);
        string? source = null, outPath = null, dump = null;
        for (int i = 0; i < rest.Length; i++)
        {
            string a = rest[i];
            bool hasVal = i + 1 < rest.Length;
            if (a == "--source" && hasVal) source = rest[++i];
            else if (a == "--out" && hasVal) outPath = rest[++i];
            else if (a == "--dump" && hasVal) dump = rest[++i];
            else { Console.Error.WriteLine($"ashfall-kit-stairs: bad argument \"{a}\" (usage: ashfall-kit-stairs [--source <dir>] [--out <file>])"); return 2; }
        }
        source ??= Path.Combine(local, "sm-reimpl", AshfallKit.PrivateFolder, "source");
        outPath ??= Path.Combine(AshfallKitCollisionCommand.FindRepoRoot(), "src", "SmSim", "Extras", "Musou", "Ashfall", "AshfallKitStairs.g.cs");
        if (!Directory.Exists(source)) { Console.Error.WriteLine($"ashfall-kit-stairs: source folder not found: {source}"); return 1; }
        var rows = new List<(string Id, List<AshfallRamp> Stairs)>();
        foreach (var model in AshfallKit.Models.Where(m => AshfallKitFit.WalkableIds.Contains(m.Id)).OrderBy(m => m.Id, StringComparer.Ordinal))
        {
            string file = Path.Combine(source, model.File.Replace('/', Path.DirectorySeparatorChar));
            if (!File.Exists(file)) { Console.Error.WriteLine($"ashfall-kit-stairs: missing {model.Id}: {file}"); return 1; }
            var mesh = GlbReader.Read(file);
            if (model.ImportFix != AshfallKitImportFix.None)
                for (int i = 0; i < mesh.Positions.Count; i++) mesh.Positions[i] = model.FileToModel(mesh.Positions[i]);
            if (dump != null && dump.Split(',').Contains(model.Id))
            {
                var (nx, nz, cell, top) = AshfallStairDetect.TopHeights(mesh.Positions, mesh.Indices, model.RawMin, model.RawMax);
                float h = model.RawMax.Y - model.RawMin.Y;
                Console.WriteLine($"{model.Id}: {nx} x {nz} cells of {cell:0.0000}, height {h:0.000} (one character = {h / 61f:0.0000})");
                const string digits = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ";
                for (int z = 0; z < nz; z++)
                {
                    var line = new StringBuilder();
                    for (int x = 0; x < nx; x++) { float t = top[x + nx * z]; line.Append(float.IsNaN(t) ? '.' : digits[Math.Clamp((int)MathF.Round(t / h * 61f), 0, 61)]); }
                    Console.WriteLine(line.ToString());
                }
            }
            AshfallStairDetect.Trace = dump != null && dump.Split(',').Contains(model.Id) ? Console.WriteLine : null;
            var stairs = AshfallStairDetect.Find(mesh.Positions, mesh.Indices, model.RawMin, model.RawMax);
            rows.Add((model.Id, stairs));
            Console.WriteLine($"{model.Id}: {stairs.Count} stair(s)" + string.Concat(stairs.Select(s => Inv($"; dir {s.Dir} {s.YLow - model.RawMin.Y:0.000}->{s.YHigh - model.RawMin.Y:0.000} over {(s.Dir < 2 ? s.Max.X - s.Min.X : s.Max.Z - s.Min.Z):0.000}, {(s.Dir < 2 ? s.Max.Z - s.Min.Z : s.Max.X - s.Min.X):0.000} wide"))));
        }
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// Generated by `smtool ashfall-kit-stairs` from the owner's Ashfall kit library (numbers only, no asset bytes). Do not edit by hand.");
        sb.AppendLine("// Late batch F (2026-11-06): each walkable model's stairs found in its own mesh (AshfallStairDetect): raw glTF frame (Y up), footprint from the first riser to the last, YLow the floor at the foot, YHigh the landing.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("using System.Numerics;");
        sb.AppendLine();
        sb.AppendLine("namespace SmSim.Extras.Musou.Ashfall;");
        sb.AppendLine();
        sb.AppendLine("public static partial class AshfallKitCollision");
        sb.AppendLine("{");
        sb.AppendLine("    static readonly Dictionary<string, AshfallRamp[]> StairData = new()");
        sb.AppendLine("    {");
        foreach (var (id, stairs) in rows)
        {
            sb.Append($"        [\"{id}\"] = [");
            sb.Append(string.Join(", ", stairs.Select(s => $"new({V(s.Min)}, {V(s.Max)}, {s.Dir}, {F(s.YLow)}, {F(s.YHigh)})")));
            sb.AppendLine("],");
        }
        sb.AppendLine("    };");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>The stairs found in a walkable model's mesh (none for other models).</summary>");
        sb.AppendLine("    public static IReadOnlyList<AshfallRamp> Stairs(string id) => StairData.TryGetValue(id, out var s) ? s : [];");
        sb.AppendLine("}");
        File.WriteAllText(outPath, sb.ToString(), new UTF8Encoding(false));
        Console.WriteLine($"ashfall-kit-stairs: {rows.Count} walkable models, {rows.Sum(r => r.Stairs.Count)} stairs -> {outPath}");
        return 0;
    }

    static string Inv(FormattableString f) => f.ToString(CultureInfo.InvariantCulture);
    static string F(float v) { v = MathF.Round(v, 4); if (v == 0f) v = 0f; return v.ToString("0.0000", CultureInfo.InvariantCulture) + "f"; }
    static string V(Vector3 v) => $"new({F(v.X)}, {F(v.Y)}, {F(v.Z)})";
}
